CREATE TABLE IF NOT EXISTS users (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, username VARCHAR(24) NOT NULL UNIQUE,
 email VARCHAR(254) NOT NULL UNIQUE, password_hash VARCHAR(255) NOT NULL, avatar_url VARCHAR(512),
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS games (
 id VARCHAR(32) PRIMARY KEY, name VARCHAR(80) NOT NULL, slug VARCHAR(32) NOT NULL UNIQUE,
 description TEXT NOT NULL, category VARCHAR(32) NOT NULL, thumbnail VARCHAR(255), is_active BOOLEAN NOT NULL DEFAULT TRUE, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS matches (
 id CHAR(36) PRIMARY KEY, game_id VARCHAR(32) NOT NULL, room_code CHAR(6) NOT NULL,
 winner_id BIGINT UNSIGNED NULL, status ENUM('completed','forfeit') NOT NULL, started_at DATETIME NOT NULL, finished_at DATETIME NOT NULL,
 FOREIGN KEY (game_id) REFERENCES games(id), FOREIGN KEY (winner_id) REFERENCES users(id) ON DELETE SET NULL,
 INDEX idx_matches_finished(finished_at), INDEX idx_matches_game(game_id,finished_at)
);
CREATE TABLE IF NOT EXISTS match_players (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, match_id CHAR(36) NOT NULL, user_id BIGINT UNSIGNED NOT NULL, player_slot TINYINT NOT NULL,
 score INT NOT NULL DEFAULT 0, result ENUM('win','loss','draw') NOT NULL,
 FOREIGN KEY (match_id) REFERENCES matches(id) ON DELETE CASCADE, FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
 UNIQUE KEY match_user(match_id,user_id), UNIQUE KEY match_slot(match_id,player_slot), INDEX idx_player_history(user_id,match_id), CHECK (player_slot IN (0,1))
);
CREATE TABLE IF NOT EXISTS player_stats (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, user_id BIGINT UNSIGNED NOT NULL, game_id VARCHAR(32) NOT NULL,
 matches_played INT UNSIGNED NOT NULL DEFAULT 0, wins INT UNSIGNED NOT NULL DEFAULT 0, losses INT UNSIGNED NOT NULL DEFAULT 0, draws INT UNSIGNED NOT NULL DEFAULT 0, rating INT NOT NULL DEFAULT 1000,
 FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE, FOREIGN KEY (game_id) REFERENCES games(id), UNIQUE KEY user_game(user_id,game_id), INDEX idx_ranking(game_id,wins,rating)
);
CREATE TABLE IF NOT EXISTS room_history (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, room_code CHAR(6) NOT NULL, game_id VARCHAR(32) NOT NULL,
 host_user_id BIGINT UNSIGNED, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, closed_at TIMESTAMP NULL,
 FOREIGN KEY (game_id) REFERENCES games(id), FOREIGN KEY (host_user_id) REFERENCES users(id) ON DELETE SET NULL, INDEX idx_room_code(room_code)
);
